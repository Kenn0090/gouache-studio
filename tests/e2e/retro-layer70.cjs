/* 0.70: the Retro (N64 / PSX) layer effect: on top of the stack for everything below, or clipped to one layer; also in 3D Paint. */
const {chromium}=require('playwright'),crypto=require('crypto');
const OLD=__dirname+'/';let fails=0;const ok=(c,m)=>{console.log((c?'PASS ':'FAIL ')+m);if(!c)fails++;};
(async()=>{const b=await chromium.launch({args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
 const p=await (await b.newContext({viewport:{width:1440,height:900}})).newPage();const errs=[];
 p.on('pageerror',e=>errs.push('PAGEERR '+e.stack));
 await p.addInitScript(()=>{try{localStorage.setItem('gs.p3d',JSON.stringify({size:128,layout:'3d'}));}catch(e){}});
 await p.route('**/*',r=>{const u=r.request().url();
  if(u.includes('pako'))return r.fulfill({path:OLD+'node_modules/pako/dist/pako.min.js',contentType:'text/javascript'});
  if(u.includes('UTIF.js'))return r.fulfill({path:OLD+'node_modules/utif/UTIF.js',contentType:'text/javascript'});
  if(u.includes('ag-psd'))return r.fulfill({path:OLD+'node_modules/ag-psd/dist/bundle.js',contentType:'text/javascript'});
  if(u.startsWith('file:'))return r.continue();return r.abort();});
 await p.goto('file://'+require('path').resolve(__dirname,'../../dist-web/index.html')+'?debug');await p.waitForTimeout(2500);
 const W=ms=>p.waitForTimeout(ms||300);
 await p.evaluate(()=>__gs.EXAMPLES[0].run());await W(1800);
 const box=await p.locator('#gl').boundingBox(),shot=async()=>crypto.createHash('md5').update(await p.screenshot({clip:box})).digest('hex');
 const h0=await shot();
 await p.evaluate(()=>__gs.cmdNewRetroLayer(false));await W(700);
 ok(await p.locator('#rt_pre_n64').count()===1,'the Retro layer opens with the console presets');
 await p.click('#dlgOk');await W(900);
 const top=await p.evaluate(()=>{const c=__gs.doc.root.children,L=c[c.length-1];return {fx:!!L.fx,id:L.fx&&L.fx.stack[0].id,clip:!!L.clip,name:L.name};});
 ok(top.fx&&top.id==='retroPixel'&&!top.clip,'it sits at the top of the stack and passes through to everything below '+JSON.stringify(top));
 const h1=await shot();ok(h1!==h0,'the whole picture turns retro');
 await p.evaluate(()=>{const c=__gs.doc.root.children;c[c.length-1].visible=false;__gs.changedAll();});await W(700);
 ok(await shot()===h0,'switching the layer off brings the picture back');
 await p.evaluate(()=>{const L=__gs.allLayers().find(l=>l.name==='Stones');__gs.selectOnly(L);__gs.renderLayers();});
 await p.evaluate(()=>__gs.cmdNewRetroLayer(true));await W(700);await p.click('#dlgOk');await W(900);
 const cl=await p.evaluate(()=>{const S=__gs.allLayers().find(l=>l.name==='Stones'),i=S.parent.children.indexOf(S),n=S.parent.children[i+1];return {clip:!!(n&&n.clip),fx:!!(n&&n.fx),id:n&&n.fx&&n.fx.stack[0].id};});
 ok(cl.clip&&cl.fx&&cl.id==='retroPixel','the clipped Retro layer sits right above the selected layer and only affects it '+JSON.stringify(cl));
 ok(await shot()!==h0,'the clipped layer changes the picture');
 await p.evaluate(()=>{const G=__gs;G.closeWelcome();G.setMode('p3d',true);G.useModel(G.primMesh('cube',1));G.cmdNewFillLayer({name:'Red',maps:{base:{c:[.85,.06,.03]}}});});await W(900);
 await p.evaluate(()=>__gs.cmdNewRetroLayer(false));await W(700);await p.click('#dlgOk');await W(900);
 ok(await p.evaluate(()=>{const c=__gs.doc.root.children,L=c[c.length-1];return !!(L.fx&&L.fx.stack[0].id==='retroPixel');}),'the Retro layer also works in 3D Paint');
 ok(errs.length===0,'no application errors '+errs.slice(0,3).join(' | '));
 await b.close();process.exit(fails?1:0);})().catch(e=>{console.error(e);process.exit(1);});
